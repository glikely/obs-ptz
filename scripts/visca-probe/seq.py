from vp import *
P=bytes.fromhex('81090400ff')  # power inq (fast)
def step(v,label,seq,payload=P,t=0.4,typ=0x0110):
    v.raw(typ,payload,seq); r=v.rx(t)
    print(f" {label:34s} sent seq={seq}:", "NO REPLY" if not r else "")
    v.show(r)
for ip in sys.argv[1:]:
    print("=====",ip)
    v=V(ip)
    print("-- reset then seq 1,2,3")
    v.raw(0x0200,b'\x01',0); v.show(v.rx(0.4))
    for s in (1,2,3): step(v,"in order",s)
    step(v,"duplicate of last (3)",3)
    step(v,"backwards (2)",2)
    step(v,"gap (+10 -> 13)",13)
    step(v,"after gap, 14",14)
    step(v,"back to 4 (low, after 14)",4)
    print("-- reset then start at seq 0")
    v.raw(0x0200,b'\x01',0); v.show(v.rx(0.4))
    step(v,"seq 0 first",0)
    step(v,"seq 1",1)
    print("-- reset then start at seq 100")
    v.raw(0x0200,b'\x01',0); v.show(v.rx(0.4))
    step(v,"seq 100 first",100)
    step(v,"seq 101",101)
    print("-- wrap")
    step(v,"seq 0xfffffffe",0xfffffffe)
    step(v,"seq 0xffffffff",0xffffffff)
    step(v,"seq 0 (wrap)",0)
    step(v,"seq 1",1)
    print("-- no reset, seq 50 (way back)")
    step(v,"seq 50",50)
    step(v,"seq 51",51)
    print("-- command type w/ inquiry payload / mismatch")
    step(v,"type 0100 w/ inquiry payload",60,typ=0x0100)
    step(v,"type 0110 w/ zoom stop cmd",61,payload=bytes.fromhex('8101040700ff'))
    v.sock.close()
